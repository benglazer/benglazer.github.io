export const VERBS = Object.freeze(verbs);
export const VERB_INDEX = new Map(VERBS.map((verb) => [verb.infinitive, verb]));

export function findVerb(infinitive) {
  return VERB_INDEX.get(infinitive.toLocaleLowerCase("es").trim());
}
