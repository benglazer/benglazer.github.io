// Accents a one-syllable form that becomes end-stressed once prefixed: ten → mantén, rio → sonrió.
function accentPrefixedForm(form) {
  if (/[áéíóú]/.test(form) || !/[aeiouns]$/.test(form)) return form;
  const nuclei = form.match(/[aeiou]+/g) || [];
  if (nuclei.length !== 1 || (nuclei[0].match(/[aeo]/g) || []).length > 1) return form;
  const strong = form.search(/[aeo]/);
  const index = strong >= 0 ? strong : form.search(/[iu][^iu]*$/);
  const accented = { a: "á", e: "é", i: "í", o: "ó", u: "ú" }[form[index]];
  return form.slice(0, index) + accented + form.slice(index + 1);
}

// Builds a prefixed verb (mantener, suponer, devolver) from its base's irregular forms.
function defineCompound(prefix, baseInfinitive, translation, level, options = {}) {
  const base = verbs.find((verb) => verb.infinitive === baseInfinitive);
  const derived = {};
  if (base.patterns) derived.patterns = base.patterns;
  if (base.forms) {
    derived.forms = Object.fromEntries(Object.entries(base.forms).map(([tense, forms]) => [
      tense,
      forms.map((form) => (form ? prefix + accentPrefixedForm(form) : form)),
    ]));
  }
  ["presentYo", "preteriteStem", "futureStem", "gerund", "participle"].forEach((key) => {
    if (base[key]) derived[key] = prefix + base[key];
  });
  return defineVerb(prefix + base.infinitive, translation, level, { ...derived, ...options });
}

